void resuelveCaso()
{
    int N;
    cin >> N;

    int w, e;
    vector<pair<int, int>> buildings(N);

    for (int i = 0; i < N; i++) {
        cin >> w >> e;
        buildings[i] = {e, w};
    }

    sort(buildings.begin(), buildings.end());

    int tunnels = 1;
    int latestTunnel = buildings[0].first - 1;
    
    for (int i = 1; i < N; i++) {
        if (buildings[i].second > latestTunnel) {
            tunnels++;
            latestTunnel = buildings[i].first - 1;
        }
    }
    
    cout << tunnels << '\n';
}

